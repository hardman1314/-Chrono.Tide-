  /// VNDB 翻译的小写键索引（用于大小写不敏感匹配）
  ///
  /// 结构：lowercase(originalKey) → translation
  /// 避免每次翻译都遍历整个 Map（O(n) → O(1)）。
  static Map<String, String>? _vndbLowerIndex;

  /// 是否已尝试加载过 VNDB 翻译资源（避免重复加载）
  static bool _vndbLoadAttempted = false;

  /// 加载 VNDB 翻译资源
  ///
  /// 应在应用启动时（如 MetadataFetcher.init）调用一次。
  /// 加载失败时静默降级到内置 [enToZh] 小表，不抛异常。
  static Future<void> initialize() async {
    if (_vndbLoadAttempted) return;
    _vndbLoadAttempted = true;

    try {
      final raw = await rootBundle.loadString(_vndbAssetPath);
      final decoded = jsonDecode(raw);
      if (decoded is! Map) return;

      final cache = <String, String>{};
      final lowerIndex = <String, String>{};

      decoded.forEach((key, value) {
        if (key is! String) return;
        // 跳过 _attribution 等元数据字段
        if (key.startsWith('_')) return;
        if (value is! String) return;
        if (value.isEmpty) return;

        cache[key] = value;
        // 构建小写索引（仅当小写键与原键不同时才记录，避免覆盖）
        final lower = key.toLowerCase();
        lowerIndex.putIfAbsent(lower, () => value);
      });

      _vndbTranslationsCache = cache;
      _vndbLowerIndex = lowerIndex;
      // ignore: avoid_print
      print('[TagTranslator] ✅ 已加载 VNDB 翻译: ${cache.length} 条');
    } catch (e) {
      // 静默降级：使用内置小表
      // ignore: avoid_print
      print('[TagTranslator] ⚠️ 加载 VNDB 翻译资源失败，降级到内置表: $e');
    }
  }

