  /// 根据数据源语言翻译标签为中文
  ///
  /// - [name] 原始标签名
  /// - [source] 数据源类型
  /// 返回翻译后的中文标签（未命中则原样返回）
  static String translate(String name, SourceType source) {
    if (name.isEmpty) return name;

    // 中文源无需翻译
    if (source == SourceType.bangumi ||
        source == SourceType.ymgal ||
        source == SourceType.steam ||
        source == SourceType.touchgal) {
      return name;
    }

    // 英文源（VNDB）
    if (source == SourceType.vndb) {
      return _translateVndb(name);
    }

    // 日文源（DLsite / ErogameScape）
    if (source == SourceType.dlsite || source == SourceType.erogamescape) {
      final translated = jaToZh[name];
      if (translated != null) return translated;
      return name; // 未命中，原样返回
    }

    return name;
  }

  /// VNDB 标签翻译（优先用大数据缓存，兜底用内置小表）
  ///
  /// 查找顺序：
  /// 1. 大数据缓存精确匹配（O(1)）
  /// 2. 大数据缓存大小写不敏感匹配（O(1)，通过预构建的 lowercase 索引）
  /// 3. 内置 [enToZh] 精确匹配（O(1)，作为大表补充覆盖）
  /// 4. 内置 [enToZh] 大小写不敏感匹配（O(n)，仅 ~200 条，性能可接受）
  /// 5. 未命中，原样返回
  ///
  /// 注意：步骤 3-4 不再受 `_vndbTranslationsCache == null` 限制，
  /// 即使大表已加载，[enToZh] 仍作为补充覆盖层（大表 ~2990 条覆盖不全时
  /// 由内置小表兜底常见标签）。
  static String _translateVndb(String name) {
    // 1. 大数据缓存精确匹配
    final cacheHit = _vndbTranslationsCache?[name];
    if (cacheHit != null) return cacheHit;

    // 2. 大数据缓存大小写不敏感匹配
    if (_vndbLowerIndex != null) {
      final lowerHit = _vndbLowerIndex![name.toLowerCase()];
      if (lowerHit != null) return lowerHit;
    }

    // 3. 内置小表精确匹配
    final builtinHit = enToZh[name];
    if (builtinHit != null) return builtinHit;

    // 4. 内置小表大小写不敏感匹配（补充覆盖，无论大表是否加载都执行）
    for (final entry in enToZh.entries) {
      if (entry.key.toLowerCase() == name.toLowerCase()) {
        return entry.value;
      }
    }

    // 5. 未命中，原样返回
    return name;
  }

  /// 批量翻译标签列表
  static List<String> translateAll(List<String> names, SourceType source) {
    return names.map((n) => translate(n, source)).toList();
  }
